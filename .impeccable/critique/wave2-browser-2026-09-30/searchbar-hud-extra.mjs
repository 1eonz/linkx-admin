writeFileSync(`${out}/searchbar-mobile-hud-reduced.json`, JSON.stringify({ name: 'searchbar-mobile-hud-reduced', meta: { mode: 'mobile-hud-reduced-motion', hudClassApplied: true }, metrics }, null, 2));
